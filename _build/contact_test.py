import asyncio, sys, json, urllib.parse
from playwright.async_api import async_playwright
BASE=sys.argv[1]; OUT=sys.argv[2]
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        c=await b.new_context(viewport={'width':393,'height':852},device_scale_factor=3,is_mobile=True,has_touch=True)
        errs=[]; res={}
        pg=await c.new_page()
        pg.on('console',lambda m: errs.append(f'{m.type}:{m.text}') if m.type in('error','warning') else None)
        pg.on('pageerror',lambda e: errs.append(f'pageerror:{e}'))
        nxt=lambda: pg.click('button[data-next]')
        # Flow 1: deer
        await pg.goto(BASE+'contact/',wait_until='networkidle'); await pg.wait_for_timeout(1800)
        await pg.screenshot(path=OUT+'contact-m-01-service.png')
        await pg.click('label.opt:has-text("Deer recovery")'); await pg.wait_for_timeout(1200)
        res['deer_step']=await pg.locator('.ct-k').first.inner_text()
        res['deer_step_count']=await pg.locator('[data-steps] li').count()
        await nxt(); await pg.wait_for_timeout(600)
        res['deer_errors_shown']=await pg.locator('.fld.err').count()
        await pg.screenshot(path=OUT+'contact-m-02-deer.png', full_page=False)
        await pg.fill('#f-name','Sam Hunter'); await pg.fill('#f-phone','765-555-0101')
        await nxt(); await pg.wait_for_timeout(1000)
        await pg.screenshot(path=OUT+'contact-m-04-review.png')
        res['deer_review']=await pg.locator('.rev').inner_text()
        await nxt(); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=OUT+'contact-m-05-done.png')
        href=await pg.get_attribute('[data-sms-link]','href'); res['deer_sms']=urllib.parse.unquote(href)
        # Flow 2: pet via deep link
        await pg.goto(BASE+'contact/?service=lost-pet-recovery',wait_until='networkidle'); await pg.wait_for_timeout(1600)
        res['pet_step']=await pg.locator('.ct-k').first.inner_text()
        await pg.click('.tchip:has-text("Dog")'); await pg.fill('#f-pname','Duke'); await pg.fill('#f-pdesc','Medium, black and tan, orange collar')
        await pg.click('[data-now=seenWhen]'); await pg.fill('#f-county','Putnam'); await pg.fill('#f-seenWhere','Near Bainbridge, US 36')
        await pg.click('.tchip:has-text("Shy")')
        await pg.wait_for_timeout(400); await pg.screenshot(path=OUT+'contact-m-06-pet.png')
        await nxt(); await pg.wait_for_timeout(1000)
        await pg.fill('#f-name','Ana'); await pg.fill('#f-phone','12')
        await nxt(); await pg.wait_for_timeout(600)
        res['bad_phone_blocked']=await pg.locator('.fld[data-k=phone].err').count()==1
        await pg.fill('#f-phone','317 555 0199'); await pg.click('.tchip:has-text("Text me")')
        await nxt(); await pg.wait_for_timeout(1000); await nxt(); await pg.wait_for_timeout(1400)
        res['pet_sms']=urllib.parse.unquote(await pg.get_attribute('[data-sms-link]','href'))
        await pg.screenshot(path=OUT+'contact-m-07-pet-done.png')
        # Flow 3: survey, with back and edit
        await pg.goto(BASE+'contact/',wait_until='networkidle'); await pg.wait_for_timeout(1500)
        await pg.click('label.opt:has-text("Herd or land survey")'); await pg.wait_for_timeout(1100)
        await pg.click('.tchip:has-text("Herd headcount")'); await pg.click('.tchip:has-text("Fence line check")'); await pg.click('.tchip:has-text("80–200")')
        await pg.click('.tchip:has-text("A headcount")'); await pg.click('.tchip:has-text("Photos")')
        await pg.fill('#f-county','Montgomery'); await pg.click('.tchip:has-text("This week")')
        await nxt(); await pg.wait_for_timeout(900)
        await pg.click('button[data-back]'); await pg.wait_for_timeout(900)
        res['back_kept']=await pg.locator('.tchip input[value="Herd headcount"]').is_checked()
        await nxt(); await pg.wait_for_timeout(900)
        await pg.fill('#f-name','Jo Farmer'); await pg.fill('#f-phone','7655550123')
        await nxt(); await pg.wait_for_timeout(1000)
        await pg.click('[data-edit="1"]'); await pg.wait_for_timeout(900)
        res['edit_step']=await pg.locator('.ct-k').first.inner_text()
        await nxt(); await pg.wait_for_timeout(900); await nxt(); await pg.wait_for_timeout(900); await nxt(); await pg.wait_for_timeout(1400)
        res['survey_sms']=urllib.parse.unquote(await pg.get_attribute('[data-sms-link]','href'))
        await pg.screenshot(path=OUT+'contact-m-08-survey-done.png')
        print(json.dumps({'res':res,'errs':errs},indent=1,ensure_ascii=False))
        await b.close()
asyncio.run(main())
